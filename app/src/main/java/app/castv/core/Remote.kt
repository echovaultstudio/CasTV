package app.castv.core

/** Things a remote button can do while watching. Users can assign any of them to any button. */
enum class RemoteAction(val label: String) {
    NONE("Nothing"),
    SHOW_CHANNELS("Show channels list"),
    SHOW_CHANNELS_GROUPS("Show channel groups"),
    SHOW_GUIDE("Show TV guide"),
    SHOW_GUIDE_GROUPS("Show TV guide groups"),
    SHOW_INFO("Show info panel"),
    SHOW_CONTROLS("Show control panel"),
    SHOW_MENU("Show menu"),
    CHANNEL_UP("Next channel"),
    CHANNEL_DOWN("Previous channel"),
    PREVIEW_NEXT("Info for next channel"),
    PREVIEW_PREVIOUS("Info for previous channel"),
    LAST_CHANNEL("Most recent channel"),
    TOGGLE_FAVORITE("Add/remove favorite"),
    PLAY_PAUSE("Play/pause"),
    STOP("Stop playback"),
    REWIND("Rewind"),
    FAST_FORWARD("Fast forward"),
    RESTART_PROGRAM("Restart current program"),
    GO_LIVE("Go to live"),
    RECORD("Start/stop recording"),
    SEARCH("Search"),
    HISTORY("History"),
    MULTIVIEW("Multiview"),
    EXTERNAL_PLAYER("Open in external player"),
    AUDIO_TRACKS("Audio tracks"),
    SUBTITLES("Subtitles"),
    DISPLAY_MODE("Change display mode"),
    SLEEP_TIMER("Sleep timer"),
    PIP("Picture-in-picture"),
    SETTINGS("Settings"),
    EXIT("Exit"),
}

/** Remote buttons that can be customised (a short press and, where it makes sense, a long press). */
enum class RemoteButton(val label: String) {
    OK("OK"), OK_LONG("Long OK"),
    UP("Up"), UP_LONG("Long Up"), DOWN("Down"), DOWN_LONG("Long Down"),
    LEFT("Left"), LEFT_LONG("Long Left"), RIGHT("Right"), RIGHT_LONG("Long Right"),
    BACK_LONG("Long Back"),
    MENU("Menu"), MENU_LONG("Long Menu"),
    CH_UP("Channel +"), CH_DOWN("Channel −"),
    PLAY_PAUSE("Play/Pause"), PLAY_PAUSE_LONG("Long Play/Pause"),
    REWIND("Rewind"), FAST_FORWARD("Fast forward"), STOP("Stop"), RECORD("Record"),
    GUIDE("Guide"), INFO("Info"),
    RED("Red"), GREEN("Green"), YELLOW("Yellow"), BLUE("Blue"),
}

object RemoteDefaults {
    val map: Map<RemoteButton, RemoteAction> = mapOf(
        RemoteButton.OK to RemoteAction.SHOW_CHANNELS,
        RemoteButton.OK_LONG to RemoteAction.SHOW_MENU,
        RemoteButton.UP to RemoteAction.CHANNEL_UP,
        RemoteButton.DOWN to RemoteAction.CHANNEL_DOWN,
        RemoteButton.UP_LONG to RemoteAction.PREVIEW_NEXT,
        RemoteButton.DOWN_LONG to RemoteAction.PREVIEW_PREVIOUS,
        RemoteButton.LEFT to RemoteAction.SHOW_CHANNELS_GROUPS,
        RemoteButton.LEFT_LONG to RemoteAction.REWIND,
        RemoteButton.RIGHT to RemoteAction.SHOW_GUIDE,
        RemoteButton.RIGHT_LONG to RemoteAction.FAST_FORWARD,
        RemoteButton.BACK_LONG to RemoteAction.LAST_CHANNEL,
        RemoteButton.MENU to RemoteAction.SHOW_MENU,
        RemoteButton.MENU_LONG to RemoteAction.SETTINGS,
        RemoteButton.CH_UP to RemoteAction.CHANNEL_UP,
        RemoteButton.CH_DOWN to RemoteAction.CHANNEL_DOWN,
        RemoteButton.PLAY_PAUSE to RemoteAction.PLAY_PAUSE,
        RemoteButton.PLAY_PAUSE_LONG to RemoteAction.RECORD,
        RemoteButton.REWIND to RemoteAction.REWIND,
        RemoteButton.FAST_FORWARD to RemoteAction.FAST_FORWARD,
        RemoteButton.STOP to RemoteAction.STOP,
        RemoteButton.RECORD to RemoteAction.RECORD,
        RemoteButton.GUIDE to RemoteAction.SHOW_GUIDE,
        RemoteButton.INFO to RemoteAction.SHOW_INFO,
        RemoteButton.RED to RemoteAction.TOGGLE_FAVORITE,
        RemoteButton.GREEN to RemoteAction.AUDIO_TRACKS,
        RemoteButton.YELLOW to RemoteAction.SUBTITLES,
        RemoteButton.BLUE to RemoteAction.MULTIVIEW,
    )
}
